"""Add links to every historical league table to the "Previous Seasons" plain page.

    python manage.py update_seasons_page            # dry run: show what would change
    python manage.py update_seasons_page --commit   # save the page

The generated section lists every season that has at least one historical league
(newest first) with links to all of that season's leagues. It sits between two
marker comments in the page body, so re-running the command replaces only that
section and leaves the hand-written seasons above it alone.

On the first run (no markers yet) any hand-written section for one of those
seasons is replaced too: everything from the first <h3> heading naming one of
them to the end of the page. Those are the oldest seasons, so they come last.
"""
import re

from django.core.management.base import BaseCommand, CommandError
from django.urls import reverse
from django.utils.html import escape

from content.models import page
from league.models import League, Season

START = "<!-- historical-tables:start (generated by manage.py update_seasons_page; edits here are overwritten) -->"
END = "<!-- historical-tables:end -->"
MARKER_RE = re.compile(r"<!-- historical-tables:start.*?-->.*?<!-- historical-tables:end -->", re.S)

DIVISION_ORDER = ["championship", "premiership", "major", "first class"]

INTRO = (
    "<p><em>Most of the league tables below were reconstructed from AGM minutes, club newsletters, "
    "printed tables and games submitted to the ECF. For those, only the final standings survive, "
    "not the individual games.</em></p>"
)

SEASON_NOTES = {
    "2019/2020": (
        "The 2019/2020 season was halted in March 2020 due to the Covid pandemic and no games were "
        "submitted to the ECF for rating after December 2019. The tables below are reconstructed from "
        "the rated games played up to then; discretionary decisions on promotion and relegation were made later."
    ),
}


def league_sort_key(league):
    name = league.name.lower()
    for i, division in enumerate(DIVISION_ORDER):
        if name == division or name == f"wallasey {division}":
            return (0, i, name)
        if name.startswith(division):  # e.g. "Premiership (alternative table)"
            return (1, i, name)
    return (2, 0, name)


class Command(BaseCommand):
    help = "Add links to the historical league tables to the Previous Seasons page (dry run unless --commit)."

    def add_arguments(self, parser):
        parser.add_argument("--slug", default="seasons", help="Slug of the plain page to update")
        parser.add_argument("--commit", action="store_true", help="Save the page. Without this nothing is written.")

    def build_block(self, seasons):
        viewer = reverse("league_history")
        parts = [
            START, "<div>",
            f'<p><a href="{viewer}"><i class="fas fa-history"></i> Browse the league tables season by season</a></p>',
            INTRO,
        ]
        for season in seasons:
            leagues = sorted(League.objects.filter(season=season), key=league_sort_key)
            parts.append(f'<h3 class="">{escape(season.name)}</h3>')
            parts.append("<p>&nbsp;</p>")
            if season.name in SEASON_NOTES:
                parts.append(f"<p>{SEASON_NOTES[season.name]}</p>")
            for league in leagues:
                url = reverse("tournament", args=[league.slug])
                parts.append(f'<h5><a href="{url}">{escape(league.name)}</a></h5>')
            parts.append("<p><br></p>")
        parts += ["</div>", END]
        return "\n".join(parts)

    def handle(self, *args, **opts):
        p = page.objects.filter(slug=opts["slug"]).first()
        if p is None:
            raise CommandError(f"No plain page with slug '{opts['slug']}'")

        seasons = list(
            Season.objects.filter(league__historical=True).distinct().order_by("-end")
        )
        if not seasons:
            raise CommandError("No historical leagues in the database - run import_historical_tables --commit first")
        block = self.build_block(seasons)
        body = p.body

        if MARKER_RE.search(body):
            new_body = MARKER_RE.sub(lambda m: block, body, count=1)
            how = "replaced the existing generated section"
        else:
            names = "|".join(re.escape(s.name) for s in seasons)
            m = re.search(rf"<h3[^>]*>(?:(?!</h3>).)*?(?:{names})", body, re.S)
            if m:
                kept = body[: m.start()]
                # close any <div> left open by cutting the hand-written HTML part-way through
                unclosed = len(re.findall(r"<div\b", kept)) - len(re.findall(r"</div>", kept))
                removed = body[m.start():]
                new_body = kept + "</div>" * max(unclosed, 0) + "\n" + block
                how = "replaced hand-written sections from the first historical season onwards"
            else:
                removed = ""
                new_body = body + "\n" + block
                how = "appended a new generated section"

        n_links = block.count("<h5>")
        self.stdout.write(f"Page '{p.title}' (/{p.slug}): {how}")
        self.stdout.write(f"{len(seasons)} seasons, {n_links} league links: "
                          f"{seasons[0].name} back to {seasons[-1].name}")
        if not MARKER_RE.search(body) and removed:
            self.stdout.write(self.style.WARNING("\nHand-written HTML that will be REMOVED:"))
            self.stdout.write(removed)
        self.stdout.write(self.style.WARNING("\nGenerated section:"))
        self.stdout.write(block)

        if new_body == body:
            self.stdout.write(self.style.SUCCESS("\nNo change needed."))
        elif opts["commit"]:
            p.body = new_body
            p.save()
            self.stdout.write(self.style.SUCCESS("\nSaved."))
        else:
            self.stdout.write(self.style.WARNING("\nDRY RUN: page not saved (rerun with --commit)."))
